/// Returns the default tier map as a deterministic `BTreeMap`.
#[must_use]
pub fn default_rule_tiers() -> BTreeMap<String, Severity> {
    DEFAULT_RULE_TIERS
        .iter()
        .map(|(id, severity)| ((*id).to_string(), *severity))
        .collect()
}

/// Looks up the default tier for an upstream rule ID, defaulting to `Warn` for
/// unknown custom rules unless overridden.
#[must_use]
pub fn default_tier_for(rule_id: &str) -> Option<Severity> {
    DEFAULT_RULE_TIERS
        .binary_search_by_key(&rule_id, |(id, _)| *id)
        .ok()
        .map(|index| DEFAULT_RULE_TIERS[index].1)
}
