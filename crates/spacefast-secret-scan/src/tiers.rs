//! Explicit tier classification for every vendored upstream Gitleaks rule.
//!
//! High-confidence, uniquely-prefixed provider secrets and cryptographic
//! private keys map to [`Severity::Block`]. Rules that match unprefixed
//! hex/base64 strings, generic assignments, or intentionally public client-side
//! keys (such as Mapbox `pk.*`, Firebase/GCP `AIza*`, or Stripe/Lob/Mailgun
//! publishable keys) map to [`Severity::Warn`].
//!
//! CI tests enforce that every rule in `vendor/gitleaks.toml` appears in
//! [`DEFAULT_RULE_TIERS`] and that no stale entries remain, so syncing a new
//! upstream `gitleaks.toml` fails closed until every new rule is triaged.

