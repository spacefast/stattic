/// File extensions and basenames never copied into or served from `public/`: PHP and server config.
const REFUSED_PUBLIC: &[&str] = &[
    "php", "phtml", "phar", "php3", "php4", "php5", "php7", "php8", "phps", "htaccess", "htpasswd", "ini", "user.ini",
];

/// Vite-compatible import query modifier (`?url`, `?raw`, `?inline`, `?meta`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Query {
    Default,
    Url,
    Raw,
    Inline,
    Meta,
}

impl Query {
    /// Splits a relative import specifier into `(path, query)`. Returns `Err(raw_query)` on an
    /// unrecognized query modifier.
    pub fn split(spec: &str) -> std::result::Result<(&str, Self), &str> {
        let Some((path, raw)) = spec.split_once('?') else {
            return Ok((spec, Self::Default));
        };
        let q = match raw {
            "url" => Self::Url,
            "raw" => Self::Raw,
            "inline" => Self::Inline,
            "meta" => Self::Meta,
            _ => return Err(raw),
        };
        Ok((path, q))
    }
}

