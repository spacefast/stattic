//! Files that components and pages import and that are not code (docs/decisions/2026-11-08-tsx-to-php.md,
//! "CSS"; docs/pages.md, "Assets"):
//! - `import "./site.css"`: a stylesheet, bundled (local `@import` + relative `url(...)`),
//!   minified, and linked (or inlined when small) on every page that reaches it;
//! - `import styles from "./note.module.css"`: a CSS module, its class selectors renamed to
//!   `<file stem>_<class>` (`note_dek`), minified, and linked/inlined like a stylesheet;
//! - `import hero from "./hero.png"` (or `.svg`, `.woff2`, `.mp4`, `.pdf`, etc.): copied into
//!   `sp/app/assets/<stem>-<hash>.<ext>`, and evaluates to its immutable URL (with intrinsic image
//!   dimensions recorded for automatic `width`/`height` on `<img>` and `<Image>`);
//! - Vite query modifiers: `?url` (explicit URL), `?raw` (UTF-8 string), `?inline` (data URI),
//!   `?meta` (`{ src, width, height, format }` for images).
//!
//! Every emitted file is named `<stem>-<hash>.<ext>` from a SHA-256 of its bytes under `sp/app/assets/`,
//! so a changed file gets a new URL and an old one never changes (1-year immutable `Cache-Control`).

