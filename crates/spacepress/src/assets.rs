/// MIME type for a font asset extension, or `None` if not a web font.
pub fn font_mime(file: &str) -> Option<&'static str> {
    let ext = file.rsplit_once('.')?.1.to_ascii_lowercase();
    match ext.as_str() {
        "woff2" => Some("font/woff2"),
        "woff" => Some("font/woff"),
        "ttf" => Some("font/ttf"),
        "otf" => Some("font/otf"),
        _ => None,
    }
}

/// Encodes `bytes` as a `data:<mime>;base64,...` URI.
pub fn data_uri(ext: &str, bytes: &[u8]) -> String {
    format!("data:{};base64,{}", mime_type(ext), base64_encode(bytes))
}

/// Decodes standard padded base64 into raw bytes, returning `None` on invalid input.
pub(crate) fn base64_decode(text: &str) -> Option<Vec<u8>> {
    let val = |b: u8| -> Option<u8> {
        match b {
            b'A'..=b'Z' => Some(b - b'A'),
            b'a'..=b'z' => Some(b - b'a' + 26),
            b'0'..=b'9' => Some(b - b'0' + 52),
            b'+' => Some(62),
            b'/' => Some(63),
            _ => None,
        }
    };
    let bytes = text.as_bytes();
    if !bytes.len().is_multiple_of(4) {
        return None;
    }
    let mut out = Vec::with_capacity(bytes.len() / 4 * 3);
    for chunk in bytes.as_chunks::<4>().0 {
        let a = val(chunk[0])?;
        let b = val(chunk[1])?;
        out.push((a << 2) | (b >> 4));
        if chunk[2] != b'=' {
            let c = val(chunk[2])?;
            out.push((b << 4) | (c >> 2));
            if chunk[3] != b'=' {
                let d = val(chunk[3])?;
                out.push((c << 6) | d);
            }
        } else if chunk[3] != b'=' {
            return None;
        }
    }
    Some(out)
}

pub(crate) fn base64_encode(bytes: &[u8]) -> String {
    const TABLE: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let a = chunk[0];
        let b = chunk.get(1).copied().unwrap_or(0);
        let c = chunk.get(2).copied().unwrap_or(0);
        let n = (u32::from(a) << 16) | (u32::from(b) << 8) | u32::from(c);
        out.push(TABLE[((n >> 18) & 63) as usize] as char);
        out.push(TABLE[((n >> 12) & 63) as usize] as char);
        out.push(if chunk.len() > 1 {
            TABLE[((n >> 6) & 63) as usize] as char
        } else {
            '='
        });
        out.push(if chunk.len() > 2 {
            TABLE[(n & 63) as usize] as char
        } else {
            '='
        });
    }
    out
}

/// Probes intrinsic `(width, height)` for raster images (via `imagesize`) and SVGs (`viewBox` or
/// `width`/`height` attributes on `<svg>`).
pub fn probe_image(ext: &str, bytes: &[u8]) -> Option<ImageMeta> {
    let ext = ext.to_ascii_lowercase();
    if ext == "svg" {
        let text = std::str::from_utf8(bytes).ok()?;
        let (width, height) = probe_svg(text)?;
        return Some(ImageMeta {
            width,
            height,
            format: "svg".to_string(),
        });
    }
    if matches!(
        ext.as_str(),
        "png" | "apng" | "jpg" | "jpeg" | "gif" | "webp" | "avif" | "ico" | "bmp" | "tif" | "tiff"
    ) {
        let size = imagesize::blob_size(bytes).ok()?;
        let (w, h) = (u32::try_from(size.width).ok()?, u32::try_from(size.height).ok()?);
        if w > 0 && h > 0 {
            let format = match ext.as_str() {
                "jpg" => "jpeg".to_string(),
                "tif" => "tiff".to_string(),
                other => other.to_string(),
            };
            return Some(ImageMeta {
                width: w,
                height: h,
                format,
            });
        }
    }
    None
}

fn probe_svg(text: &str) -> Option<(u32, u32)> {
    let lower = text.to_ascii_lowercase();
    let start = lower.find("<svg")?;
    let rest = &text[start..];
    let end = rest.find('>')?;
    let tag = &rest[..end];
    let attr = |name: &str| -> Option<&str> {
        let tag_lower = tag.to_ascii_lowercase();
        let needle = format!("{name}=");
        let mut from = 0;
        while let Some(pos) = tag_lower[from..].find(&needle) {
            let abs = from + pos;
            if abs > 0 && !tag.as_bytes()[abs - 1].is_ascii_whitespace() {
                from = abs + needle.len();
                continue;
            }
            let after = &tag[abs + needle.len()..];
            let quote = after.as_bytes().first().copied()?;
            if quote == b'"' || quote == b'\'' {
                let inner = &after[1..];
                let close = inner.find(quote as char)?;
                return Some(&inner[..close]);
            }
            return None;
        }
        None
    };
    let parse_len = |raw: &str| -> Option<u32> {
        let s = raw.trim();
        let s = s.strip_suffix("px").unwrap_or(s).trim();
        let n: f64 = s.parse().ok()?;
        (n > 0.0 && n.is_finite()).then_some(n.round() as u32)
    };
    if let (Some(w), Some(h)) = (attr("width").and_then(parse_len), attr("height").and_then(parse_len)) {
        return Some((w, h));
    }
    let vb = attr("viewbox")?;
    let nums: Vec<f64> = vb
        .split(|c: char| c.is_ascii_whitespace() || c == ',')
        .filter(|s| !s.is_empty())
        .filter_map(|s| s.parse::<f64>().ok())
        .collect();
    if nums.len() == 4 && nums[2] > 0.0 && nums[3] > 0.0 {
        return Some((nums[2].round() as u32, nums[3].round() as u32));
    }
    None
}

#[derive(Debug, Clone)]
pub struct Asset {
    pub kind: Kind,
    /// The source path, relative to the project root.
    pub source: String,
    /// The output file name below [`DIR`] (empty for `Kind::Raw` / `Kind::Inline`).
    pub file: String,
    /// The output bytes (minified CSS for stylesheets, raw bytes for static files).
    pub bytes: Vec<u8>,
    /// Compile-time string constant for `Kind::Raw` and `Kind::Inline`.
    pub text: Option<String>,
    /// Intrinsic image dimensions when known (for `Kind::File` and `Kind::Meta`).
    pub meta: Option<ImageMeta>,
    /// `@font-face` preloads referenced by this stylesheet.
    pub preloads: Vec<FontPreload>,
    /// A CSS module's classes: source name → output name, in selector order.
    pub classes: IndexMap<String, String>,
    /// A CSS module's un-renamed (post-`@import` & `url()`) text, for `dedupe()`.
    original: Option<String>,
}

impl Asset {
    /// Whether this asset writes a file into `sp/app/assets/`.
    pub fn emits_file(&self) -> bool {
        !matches!(self.kind, Kind::Raw | Kind::Inline) && !self.file.is_empty()
    }
}

/// A file stem as a CSS identifier part: `my-card.module.css` → `my_card`, as esbuild names it.
fn stem(source: &str, kind: Kind) -> String {
    let name = source.rsplit('/').next().unwrap_or(source);
    let base = match kind {
        Kind::CssModule => &name[..name.len() - ".module.css".len()],
        _ => name.rsplit_once('.').map_or(name, |(b, _)| b),
    };
    let out: String = base
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' })
        .collect();
    if out.is_empty() { "asset".into() } else { out }
}

fn hash(bytes: &[u8]) -> String {
    crate::hex(&Sha256::digest(bytes)[..8])
}

#[cfg(feature = "cli")]
pub(crate) fn is_javascript(path: &str) -> bool {
    path.rsplit_once('.')
        .is_some_and(|(_, extension)| extension.eq_ignore_ascii_case("js") || extension.eq_ignore_ascii_case("mjs"))
}

impl Asset {
    /// Reads one imported file. `file` is the diagnostic file id of its text.
    pub fn new(source: &str, kind: Kind, bytes: Vec<u8>, file: u32) -> Result<Self> {
        Self::with_preloads(source, kind, bytes, file, Vec::new())
    }

    pub fn with_preloads(
        source: &str,
        kind: Kind,
        bytes: Vec<u8>,
        file: u32,
        preloads: Vec<FontPreload>,
    ) -> Result<Self> {
        let mut classes = IndexMap::new();
        let mut original = None;
        let extension = match kind {
            Kind::Css | Kind::CssModule => "css".to_string(),
            _ => source.rsplit_once('.').map_or("bin", |(_, e)| e).to_ascii_lowercase(),
        };
        if kind == Kind::Raw {
            let text = String::from_utf8(bytes).map_err(|_| {
                Diag::new(
                    Span { file, start: 0, end: 0 },
                    format!("{source}?raw isn't UTF-8 text"),
                )
                .help("use `?inline` for a base64 data URI, or import the file directly for its URL")
                .code(crate::diag::Code::Import)
            })?;
            return Ok(Asset {
                kind,
                source: source.to_string(),
                file: String::new(),
                bytes: Vec::new(),
                text: Some(text),
                meta: None,
                preloads: Vec::new(),
                classes,
                original: None,
            });
        }
        if kind == Kind::Inline {
            let uri = data_uri(&extension, &bytes);
            return Ok(Asset {
                kind,
                source: source.to_string(),
                file: String::new(),
                bytes: Vec::new(),
                text: Some(uri),
                meta: None,
                preloads: Vec::new(),
                classes,
                original: None,
            });
        }
        let meta = match kind {
            Kind::File | Kind::Meta => probe_image(&extension, &bytes),
            _ => None,
        };
        let bytes = match kind {
            Kind::File | Kind::Meta => bytes,
            Kind::Css | Kind::CssModule => {
                let text = String::from_utf8(bytes).map_err(|_| {
                    Diag::new(Span { file, start: 0, end: 0 }, format!("{source} isn't UTF-8 text"))
                        .code(crate::diag::Code::Import)
                })?;
                let scanned = crate::css::scan(&text, kind == Kind::CssModule).map_err(|r| {
                    Diag::new(
                        Span {
                            file,
                            start: r.at as u32,
                            end: r.at as u32 + 1,
                        },
                        r.message,
                    )
                    .help(r.help)
                    .code(crate::diag::Code::Import)
                })?;
                if kind == Kind::CssModule {
                    let prefix = stem(source, kind);
                    for (_, _, class) in &scanned.classes {
                        classes
                            .entry(class.clone())
                            .or_insert_with(|| format!("{prefix}_{class}"));
                    }
                    let renamed = crate::css::rename(&text, &scanned, |c| classes[c].clone());
                    original = Some(text);
                    crate::css::minify(&renamed).into_bytes()
                } else {
                    crate::css::minify(&text).into_bytes()
                }
            }
            Kind::Raw | Kind::Inline => unreachable!(),
        };
        Ok(Asset {
            kind,
            source: source.to_string(),
            file: format!("{}-{}.{extension}", stem(source, kind).replace('_', "-"), hash(&bytes)),
            bytes,
            text: None,
            meta,
            preloads,
            classes,
            original,
        })
    }
}

/// Two CSS modules may give a class the same output name (`a/note.module.css` and
/// `b/note.module.css` both define `.title`). The later one, in source-path order, takes a
/// numbered name (`note_title2`), as esbuild numbers them; the renamed text and its file name follow.
pub fn dedupe(assets: &mut [&mut Asset]) {
    assets.sort_by(|a, b| a.source.cmp(&b.source));
    let mut taken: std::collections::HashSet<String> = std::collections::HashSet::new();
    for asset in assets.iter_mut() {
        if asset.kind != Kind::CssModule {
            continue;
        }
        let mut renamed = false;
        for (_, out) in asset.classes.iter_mut() {
            if taken.insert(out.clone()) {
                continue;
            }
            let mut n = 2;
            while taken.contains(&format!("{out}{n}")) {
                n += 1;
            }
            *out = format!("{out}{n}");
            taken.insert(out.clone());
            renamed = true;
        }
        if renamed {
            let original = asset.original.as_deref().expect("a CSS module keeps its text");
            let scanned = crate::css::scan(original, true).expect("scanned once already");
            let text = crate::css::rename(original, &scanned, |c| asset.classes[c].clone());
            asset.bytes = crate::css::minify(&text).into_bytes();
            asset.file = format!(
                "{}-{}.css",
                stem(&asset.source, asset.kind).replace('_', "-"),
                hash(&asset.bytes)
            );
        }
    }
}

/// The URL a stylesheet `@spacepress/frontend` builds has before its first build, followed by
/// its source path. Nothing is ever served there: [`require_frontend_styles`] refuses it.
pub(crate) const UNBUILT_STYLE: &str = "/spacepress-styles/unbuilt/";

/// The route graph can refer to stylesheets that the frontend build put in public/. A command that
/// writes the site checks they are there; `check` compiles without them.
pub(crate) fn require_frontend_styles(program: &crate::loader::Program, present: impl Fn(&str) -> bool) -> Result<()> {
    let missing = program
        .assets
        .values()
        .filter(|asset| {
            asset.file.starts_with('/') && (asset.file.starts_with(UNBUILT_STYLE) || !present(&asset.file[1..]))
        })
        .min_by(|a, b| a.file.cmp(&b.file));
    if let Some(asset) = missing {
        let message = if asset.file.starts_with(UNBUILT_STYLE) {
            format!("frontend stylesheet {} has not been built", asset.source)
        } else {
            format!("frontend stylesheet {} is missing from public/", asset.file)
        };
        return Err(Diag::new(Span::NONE, message)
            .help("Build and capture the project with its installed frontend dependency before publishing.")
            .code(crate::diag::Code::Import));
    }
    Ok(())
}

/// The stylesheets a route links: every CSS and CSS-module asset its layouts and page reach
/// through imports, each once, dependencies before the module that imports them and in import
/// order (as a bundler orders them), the root layout's first.
pub fn stylesheets(program: &crate::loader::Program, roots: &[usize]) -> Vec<String> {
    let mut out = Vec::new();
    let mut seen = std::collections::HashSet::new();
    visit_stylesheets(program, roots, &mut seen, &mut |asset| {
        out.push(asset.file.clone());
    });
    out
}

/// The `@font-face` font preloads reachable from a route's stylesheets, deduplicated in order.
pub fn preloads(program: &crate::loader::Program, roots: &[usize]) -> Vec<FontPreload> {
    let mut out = Vec::new();
    let mut seen_mods = std::collections::HashSet::new();
    let mut seen_files = std::collections::HashSet::new();
    visit_stylesheets(program, roots, &mut seen_mods, &mut |asset| {
        for preload in &asset.preloads {
            if seen_files.insert(preload.file.clone()) {
                out.push(preload.clone());
            }
        }
    });
    out
}

fn visit_stylesheets(
    program: &crate::loader::Program,
    roots: &[usize],
    seen: &mut std::collections::HashSet<usize>,
    on_sheet: &mut impl FnMut(&Asset),
) {
    fn visit(
        program: &crate::loader::Program,
        id: usize,
        seen: &mut std::collections::HashSet<usize>,
        on_sheet: &mut impl FnMut(&Asset),
    ) {
        if !seen.insert(id) {
            return;
        }
        if let Some(asset) = program.assets.get(&id) {
            if matches!(asset.kind, Kind::Css | Kind::CssModule) {
                on_sheet(asset);
            }
            return;
        }
        for stmt in &program.modules[id].body {
            let source = match stmt {
                crate::ir::Stmt::Import {
                    source,
                    type_only: false,
                    ..
                }
                | crate::ir::Stmt::ExportNames { from: Some(source), .. }
                | crate::ir::Stmt::ExportAll { from: source, .. } => source,
                _ => continue,
            };
            if let Some(&target) = program.resolved.get(&(id, source.clone())) {
                visit(program, target, seen, on_sheet);
            }
        }
    }
    for &root in roots {
        visit(program, root, seen, on_sheet);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn asset(source: &str, text: &str) -> Asset {
        Asset::new(source, kind(Path::new(source)).unwrap(), text.as_bytes().to_vec(), 0).unwrap()
    }

    #[test]
    fn css_module_classes_take_the_file_stem_as_packages_pages_named_them() {
        let a = asset(
            "sp/app/notes/[slug]/note.module.css",
            ".note { a: 1 }\n.dek, .note .back { b: 2 }\n",
        );
        assert_eq!(
            a.classes
                .iter()
                .map(|(k, v)| (k.as_str(), v.as_str()))
                .collect::<Vec<_>>(),
            [("note", "note_note"), ("dek", "note_dek"), ("back", "note_back")]
        );
        assert_eq!(
            String::from_utf8(a.bytes.clone()).unwrap(),
            ".note_note{a:1}.note_dek,.note_note .note_back{b:2}"
        );
        assert!(a.file.starts_with("note-") && a.file.ends_with(".css"), "{}", a.file);
        assert_eq!(stem("sp/components/my-card.module.css", Kind::CssModule), "my_card");
        assert_eq!(stem("sp/components/Nav.Item.module.css", Kind::CssModule), "Nav_Item");
    }

    #[test]
    fn a_class_two_modules_share_gets_a_number_in_the_later_one() {
        let mut a = asset("sp/components/b/note.module.css", ".title { color: blue }");
        let mut b = asset("sp/components/a/note.module.css", ".title { color: red } .x {}");
        let before = b.file.clone();
        dedupe(&mut [&mut a, &mut b]);
        assert_eq!(b.classes["title"], "note_title", "a/ sorts first and keeps the name");
        assert_eq!(a.classes["title"], "note_title2");
        assert_eq!(String::from_utf8(a.bytes.clone()).unwrap(), ".note_title2{color:blue}");
        assert_eq!(b.file, before);
    }

    #[test]
    fn names_follow_the_bytes() {
        let a = asset("sp/app/site.css", "body { margin: 0 }");
        let b = asset("sp/app/site.css", "body { margin: 1px }");
        assert_ne!(a.file, b.file);
        assert!(a.file.starts_with("site-"));
        let svg = Asset::new(
            "sp/app/about/compass.svg",
            Kind::File,
            b"<svg viewBox=\"0 0 64 48\"/>".to_vec(),
            0,
        )
        .unwrap();
        assert!(svg.file.starts_with("compass-") && svg.file.ends_with(".svg"));
        assert_eq!(
            svg.meta,
            Some(ImageMeta {
                width: 64,
                height: 48,
                format: "svg".into()
            })
        );
        // Minimal 1x2 PNG header (IHDR width=1, height=2).
        let png_bytes = vec![
            0x89, b'P', b'N', b'G', 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, b'I', b'H', b'D', b'R', 0x00, 0x00,
            0x00, 0x01, 0x00, 0x00, 0x00, 0x02, 0x08, 0x02, 0x00, 0x00, 0x00,
        ];
        let png = Asset::new("sp/app/about/hero.png", Kind::File, png_bytes.clone(), 0).unwrap();
        assert!(png.file.starts_with("hero-") && png.file.ends_with(".png"));
        assert_eq!(
            png.meta,
            Some(ImageMeta {
                width: 1,
                height: 2,
                format: "png".into()
            })
        );
        let inline = Asset::new("sp/app/about/hero.png", Kind::Inline, png_bytes, 0).unwrap();
        assert!(!inline.emits_file());
        assert!(inline.text.as_deref().unwrap().starts_with("data:image/png;base64,"));
        assert_eq!(kind(Path::new("font.woff2")), Some(Kind::File));
        assert_eq!(kind(Path::new("clip.mp4")), Some(Kind::File));
        assert_eq!(kind(Path::new(".hidden.png")), None);
        assert_eq!(kind(Path::new("data.json")), None);
        assert_eq!(kind(Path::new("evil.php")), None);
    }
}
