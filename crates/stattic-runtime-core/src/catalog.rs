    /// The migration recovers what a pre-catalog version recorded: served
    /// identity from `files`, source identity from `originalShas` with the size
    /// read back off the CAS object — or, for bytes the tier has demoted to S3,
    /// off the sidecar that outlives the body — visibility fail-closed against
    /// the recorded public set, and the sparse per-channel overrides.
    #[test]
    fn the_migration_projects_a_finalized_version_onto_the_catalog() {
        let temp = tempdir().unwrap();
        let blobs = temp.path().join("blobs");
        let original = b"<h1>uploaded</h1>";
        let original_sha = crate::finalize::sha256(original);
        let blob = blob_path(&blobs, &original_sha);
        fs::create_dir_all(blob.parent().unwrap()).unwrap();
        fs::write(&blob, original).unwrap();
        // `hero.png` is just as live, but the tier moved its bytes to S3 and
        // released the local body. All that is left is the demote sidecar, in
        // the shape `runtime/engine/admin/tier.php` writes it.
        let demoted_sha = "6".repeat(64);
        let demoted = blob_path(&blobs, &demoted_sha);
        fs::create_dir_all(demoted.parent().unwrap()).unwrap();
        fs::write(
            demoted.with_file_name(format!("{demoted_sha}{BLOB_DEMOTE_MARK_SUFFIX}")),
            json!({"reason": "demote", "bytes": 4096, "demoted_at": "2026-08-11T09:14:00+00:00"})
                .to_string(),
        )
        .unwrap();

        let metadata = json!({
            "spaceId": "spc_1",
            "versionId": "ver_1",
            "files": {
                "index.html": {"sha256": "1".repeat(64), "size": 22, "mime": "text/html; charset=utf-8"},
                "sf.jsonc": {"sha256": "2".repeat(64), "size": 2, "mime": "application/json; charset=utf-8"},
                "drafts/notes.md": {"sha256": "3".repeat(64), "size": 7, "mime": "text/markdown; charset=utf-8"},
                "hero.png": {"sha256": "5".repeat(64), "size": 4096, "mime": "image/png"},
            },
            // The content pipeline held `drafts/notes.md` back; nothing in the
            // document says why, which is exactly why the recorded set binds.
            "publicFiles": ["index.html", "hero.png"],
            "originalShas": {"index.html": original_sha, "hero.png": demoted_sha},
            "templateVariants": {
                "production": {
                    "index.html": {"sha256": "4".repeat(64), "size": 30, "mime": "text/html; charset=utf-8"},
                    "sf.jsonc": {"sha256": "2".repeat(64), "size": 2, "mime": "application/json; charset=utf-8"},
                }
            },
        });

        let catalog = catalog_from_metadata(&metadata, &blobs).unwrap();

        assert_eq!(catalog.format, FILE_CATALOG_FORMAT);
        assert_eq!(catalog.paths["index.html"].source.sha256, original_sha);
        assert_eq!(
            catalog.paths["index.html"].source.size,
            original.len() as u64
        );
        assert_eq!(
            catalog.paths["index.html"].served.as_ref().unwrap().sha256,
            "1".repeat(64)
        );
        assert_eq!(
            catalog.paths["hero.png"].source,
            ObjectIdentity {
                sha256: demoted_sha,
                size: 4096,
                content_type: "image/png".into(),
            },
            "a demoted source object is a live CAS member, sized from its sidecar"
        );
        assert!(!catalog.paths["sf.jsonc"].public);
        assert!(!catalog.paths["drafts/notes.md"].public);
        assert!(catalog.paths["drafts/notes.md"].served.is_none());
        assert_eq!(
            catalog.variants["production"].keys().collect::<Vec<_>>(),
            vec!["index.html"],
            "an unchanged path in a channel's file map is not an override"
        );

        // The sweep writes it into the version in place and is idempotent.
        let version = temp.path().join("spaces/spc_1/versions/ver_1");
        fs::create_dir_all(&version).unwrap();
        write_json(&version.join("metadata.json"), &metadata).unwrap();
        fs::rename(&blobs, temp.path().join("spaces/spc_1/blobs")).unwrap();

        let report = transform_private_root(temp.path()).unwrap();
        assert_eq!((report.transformed, report.failed), (1, 0));
        assert_eq!(
            read_version_catalog(&version).unwrap().as_ref(),
            Some(&catalog)
        );
        let again = transform_private_root(temp.path()).unwrap();
        assert_eq!((again.transformed, again.already_present), (0, 1));
    }

    /// A version whose uploaded object left the CAS cannot be projected, and the
    /// sweep reports it instead of writing a catalog that names bytes nobody
    /// has. Coverage has to be exact before the control plane cuts over.
    #[test]
    fn the_migration_reports_a_version_it_cannot_project() {
        let temp = tempdir().unwrap();
        let version = temp.path().join("spaces/spc_1/versions/ver_1");
        fs::create_dir_all(&version).unwrap();
        write_json(
            &version.join("metadata.json"),
            &json!({
                "spaceId": "spc_1",
                "versionId": "ver_1",
                "files": {"index.html": {"sha256": "1".repeat(64), "size": 3, "mime": "text/html"}},
                "publicFiles": ["index.html"],
                "originalShas": {"index.html": "9".repeat(64)},
            }),
        )
        .unwrap();

        let report = transform_private_root(temp.path()).unwrap();
        assert_eq!((report.transformed, report.failed), (0, 1));
        assert_eq!(report.versions[0].outcome, TransformOutcome::Failed);
        assert!(report.versions[0]
            .reason
            .as_deref()
            .unwrap_or_default()
            .contains("runtime_file_catalog_invalid"));
        assert!(read_version_catalog(&version).unwrap().is_none());
    }

    /// A delete can take the version between the read that projects the catalog
    /// and the write that publishes it. The write must refuse: the atomic writer
    /// used to `create_dir_all` its way back into existence, leaving a version
    /// directory nobody owns that the runtime would serve.
    #[test]
    fn the_migration_refuses_a_version_deleted_under_it() {
        let temp = tempdir().unwrap();
        let version = temp.path().join("spaces/spc_1/versions/ver_1");
        fs::create_dir_all(&version).unwrap();
        let metadata = json!({
            "spaceId": "spc_1",
            "versionId": "ver_1",
            "files": {"index.html": {"sha256": "1".repeat(64), "size": 3, "mime": "text/html"}},
            "publicFiles": ["index.html"],
        });
        write_json(&version.join("metadata.json"), &metadata).unwrap();
        let catalog = catalog_from_metadata(&metadata, &temp.path().join("blobs")).unwrap();

        fs::remove_dir_all(&version).unwrap();
        let error = commit_transformed_catalog(&version, &catalog).unwrap_err();

        assert!(
            error.to_string().contains("runtime_version_deleted"),
            "the sweep report has to name the race: {error}"
        );
        assert!(
            !version.exists(),
            "the transform resurrected a dead version"
        );
    }
