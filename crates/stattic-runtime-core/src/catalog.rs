//! The canonical path-keyed file catalog: the one record of what a version
//! holds, what it serves, and who may see it.
//!
//! A path names its **source** object (the byte the publisher uploaded, before
//! any transform rewrote it), its **served** object (the immutable byte this
//! version answers with, `null` when the path is held privately), its
//! visibility, and — per channel — the variant object that channel serves
//! instead of the base. It replaces the overlapping `files`, `manifest`,
//! `publicFiles`, `originalShas` and `templateVariants` projections, which
//! finalize keeps emitting until each of their readers has rehomed.
//!
//! Two rules the shape must keep:
//!
//! * Content hashes stay plain JSON strings — never split, prefixed, or
//!   wrapped. The blob collector sweeps every 64-hex string it finds in a
//!   version's declarations down to 12 nesting levels
//!   (`runtime/engine/admin/tier.php`) and is deliberately shape-agnostic so a
//!   schema change cannot make it delete live bytes.
//! * The catalog rides INSIDE `metadata.json`, under one `catalog` key — never
//!   as a sibling document. The blob collector decides liveness by sweeping
//!   that ONE document; a hash in a sibling file would be invisible to it and
//!   its blob collected while the catalog still names it. Riding inside the
//!   swept document is what lets the five legacy maps drop without teaching
//!   the collector anything.

