    /// A content-addressed name is never purged when it appears or disappears:
    /// no cache ever held the new name, and evicting the old one drops chunks a
    /// page still loading needs. It still counts as an add or a removal. The
    /// verdict is [`compiled_cache_class`]'s — this test adds the purge-side
    /// cases: a hashed DOCUMENT still purges, and a rule re-pinning a
    /// guaranteed prefix to mutable purges again.
    #[test]
    fn immutable_assets_count_but_are_not_purged() {
        let previous = catalog_for(&[
            ("_next/static/a.js", b"a"),
            ("assets/old.js", b"old"),
            ("static/chunk-XK2FA9.css", b"old chunk"),
            ("page.ab12cd34.html", b"old page"),
            ("_app/immutable/old.js", b"old pinned"),
        ]);
        let next = catalog_for(&[
            ("_next/static/b.js", b"b"),
            ("assets/new.js", b"new"),
            ("static/chunk-YT4QB7.css", b"new chunk"),
            ("page.cd34ef56.html", b"new page"),
            ("_app/immutable/new.js", b"new pinned"),
        ]);
        let declared = ImmutablePaths::from_header_rules(
            &Map::new(),
            &[
                json!({
                    "regex": "^/assets/.*$",
                    "order": 0,
                    "operations": [
                        {"kind": "set", "name": "Cache-Control", "value": "public, max-age=31536000, immutable"}
                    ],
                }),
                // The publisher re-pinned a guaranteed-immutable prefix to a
                // revalidating policy; the serve path honors the rule, so the
                // purge must too.
                json!({
                    "regex": "^/_app/immutable/.*$",
                    "order": 1,
                    "operations": [
                        {"kind": "set", "name": "Cache-Control", "value": "public, max-age=0, must-revalidate"}
                    ],
                }),
            ],
        );

        let delta = catalog_delta(&previous, &next, &static_serving(), &declared);
        assert_eq!((delta.added, delta.changed, delta.removed), (5, 0, 5));
        // The hashed *document* still purges (with its extensionless alias):
        // its URL serves the html class, never the immutable one.
        assert_eq!(
            delta.changed_paths,
            Some(vec![
                "/_app/immutable/new.js".to_string(),
                "/_app/immutable/old.js".into(),
                "/page.ab12cd34".into(),
                "/page.ab12cd34.html".into(),
                "/page.cd34ef56".into(),
                "/page.cd34ef56.html".into(),
            ])
        );
    }

