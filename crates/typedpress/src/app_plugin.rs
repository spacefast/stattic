//! The generated app plugin, `typedpress-app-<name>`: every file in it, as (path below the plugins
//! directory, bytes). `typedpress build` writes these files (`emit::emit_generated`) and the browser
//! compiler returns them (`wasm::compile`), so both make the same plugin. Its templates are compiled
//! in here, not read from the embedded runtime, which the browser build doesn't carry.

use crate::{pipeline::Built, platform, schema};

const TEMPLATE: &str = include_str!("../runtime/wp-plugin/typedpress-app.php");
const UNINSTALL: &[u8] = include_bytes!("../runtime/wp-plugin/typedpress-app-uninstall.php");
const LICENSE: &[u8] = include_bytes!("../runtime/TypedPress/LICENSE");

/// Packages the app plugin's files and renders `schema.php`: writes `tp/app/public-files.json`
/// (manifest of safe root-symlinkable `public/` files and their 12-hex content digests) and copies
/// only safe `public/` files (never PHP or dotfiles outside `.well-known/`), plus `public/.htaccess`.
pub(crate) fn package(
    built: &Built,
    migrations: impl IntoIterator<Item = (String, Vec<u8>)>,
    public: Vec<(String, Vec<u8>)>,
) -> (String, Vec<(String, Vec<u8>)>) {
    use sha2::{Digest, Sha256};

    // Literal `tp/app/` page paths win over a `public/` file of the same path.
    let literal_pages: std::collections::HashSet<String> = built
        .schema
        .app
        .as_ref()
        .map(|app| {
            app.routes
                .iter()
                .filter(|r| r.page.is_some() && !r.pattern.contains(':') && !r.pattern.contains('*'))
                .map(|r| r.pattern.trim_matches('/').to_string())
                .collect()
        })
        .unwrap_or_default();

    let mut manifest: std::collections::BTreeMap<String, String> = std::collections::BTreeMap::new();
    for (path, bytes) in &public {
        if !crate::assets::root_public_path(path) {
            continue;
        }
        let page_key = path.strip_suffix("/index.html").unwrap_or(path).trim_matches('/');
        if literal_pages.contains(page_key) {
            continue;
        }
        manifest.insert(path.clone(), crate::hex(&Sha256::digest(bytes)[..6]));
    }

    let schema_php = crate::schema_php::render(&built.schema);
    let files = build_files(built, &built.schema, &schema_php, migrations, public, &manifest);
    (schema_php, files)
}

/// The app plugin's files. `migrations` are the ledger's files by name (only `.sql` ones go in);
/// `public` holds the project's `public/` files by path below it.
fn build_files(
    built: &Built,
    schema: &schema::Schema,
    schema_php: &str,
    migrations: impl IntoIterator<Item = (String, Vec<u8>)>,
    public: Vec<(String, Vec<u8>)>,
    manifest: &std::collections::BTreeMap<String, String>,
) -> Vec<(String, Vec<u8>)> {
    let slug = format!("typedpress-app-{}", schema.name);
    let vars = plugin_vars(schema, schema_php);
    let at = |rel: &str| format!("{slug}/{rel}");
    let mut files = vec![
        (at(&format!("{slug}.php")), substitute(TEMPLATE, &vars).into_bytes()),
        (at("uninstall.php"), UNINSTALL.to_vec()),
        (at("readme.txt"), readme(&slug).into_bytes()),
        // The app plugin declares GPL-2.0-or-later like the runtime it extends; carry the text.
        (at("LICENSE"), LICENSE.to_vec()),
        (at("tp/app/schema.php"), schema_php.as_bytes().to_vec()),
    ];
    if let Some(wpml) = crate::wpml_config::render(schema) {
        files.push((at("wpml-config.xml"), wpml.into_bytes()));
    }
    files.push((at("tp/app/functions.php"), built.functions_php.as_bytes().to_vec()));
    // Public file manifest: always written (even `{}`) so removing the last `public/` file
    // overwrites any stale manifest on disk and triggers root-symlink cleanup.
    files.push((
        at("tp/app/public-files.json"),
        serde_json::to_vec(manifest).expect("public files manifest serializes"),
    ));
    if let Some(references) = &built.references {
        let php = format!(
            "<?php\n\n// Generated by `typedpress build`. Do not edit.\n\ndeclare(strict_types=1);\n\nreturn {};\n",
            crate::compile::php_json(references)
        );
        files.push((at("tp/app/references.php"), php.into_bytes()));
    }
    // The API's description, which the site serves at /wp-json/typedpress/v1/openapi.json (TypedPress\OpenApi).
    files.push((
        at("tp/app/openapi.json"),
        crate::openapi::render(&built.openapi).into_bytes(),
    ));
    // The project's styles (`tp/theme.json`), which the runtime merges over the active theme's
    // theme.json, below the site owner's Global Styles (TypedPress\Wp\ThemeStyles).
    if let Some(theme) = &built.theme {
        files.push((
            at(crate::theme::SHIPPED),
            (serde_json::to_string_pretty(theme).expect("JSON") + "\n").into_bytes(),
        ));
    }
    // Each `page.md`'s Markdown, which the site stores as a WordPress Page on its first request.
    if let Some(bodies) = crate::content_page::bodies_php(schema) {
        files.push((at("tp/app/content.php"), bodies.into_bytes()));
    }
    // The typed client as a browser module (`@typedpress/client`): what keeps a page's data live, so it
    // polls and subscribes with the same code every other caller of the API runs.
    if let Some((_, js)) = built.client_files.iter().find(|(name, _)| name == "client.js") {
        // Minified for the browser; tp/_generated/client/client.js keeps the readable source.
        let js = crate::minify::module(&String::from_utf8_lossy(js)).into_bytes();
        // Its name is fixed, so the page loads it with this digest of its bytes as the version
        // (`TypedPress\Islands::registerClient`): a new build's client is never an old cached copy.
        use sha2::Digest;
        let version = crate::hex(&sha2::Sha256::digest(&js)[..6]);
        files.push((at("tp/app/client/typedpress-client.js"), js));
        files.push((
            at("tp/app/client-version.php"),
            format!("<?php\n\n// Generated by `typedpress build`. Do not edit.\n\nreturn '{version}';\n").into_bytes(),
        ));
    }
    // Compiled `"use client"` stores, which the page loads as script modules (generator B).
    for island in schema.islands.values() {
        files.push((
            at(&format!("tp/app/client/{}", island.file)),
            island.shipped.as_bytes().to_vec(),
        ));
    }
    // Those are named by their bytes (`stem.<12 hex>.js`): browsers may keep them for good.
    if !schema.islands.is_empty() {
        files.push((at("tp/app/client/.htaccess"), CLIENT_HTACCESS.as_bytes().to_vec()));
    }
    // Imported stylesheets and images, named by their bytes (`crate::assets`).
    if !schema.assets.is_empty() {
        files.push((
            at(&format!("{}/.htaccess", crate::assets::DIR)),
            crate::assets::HTACCESS.as_bytes().to_vec(),
        ));
        for (name, bytes) in &schema.assets {
            files.push((at(&format!("{}/{name}", crate::assets::DIR)), bytes.clone()));
        }
    }
    for (rel, bytes) in migrations {
        if let Some((id, file)) = rel.split_once('/')
            && !id.is_empty()
            && !id.contains("..")
            && !file.contains('/')
            && matches!(file, "migration.sql" | "ops.json")
        {
            files.push((at(&format!("tp/app/migrations/{id}/{file}")), bytes));
        }
    }
    let mut has_public = false;
    for (rel, bytes) in public {
        if crate::assets::shippable_public_path(&rel) {
            has_public = true;
            files.push((at(&format!("public/{rel}")), bytes));
        }
    }
    if has_public {
        files.push((
            at("public/.htaccess"),
            crate::assets::PUBLIC_HTACCESS.as_bytes().to_vec(),
        ));
    }
    files
}

/// The cache header for the content-hashed store modules in `tp/app/client/`, as
/// `crate::assets::HTACCESS` gives the hashed assets; `typedpress-client.js` has a fixed name and a
/// version instead, so it is left out.
const CLIENT_HTACCESS: &str = "# Generated by `typedpress build`. Each store module here is named by a hash of its bytes.\n<FilesMatch \"\\.[0-9a-f]{12}\\.js$\">\n  <IfModule mod_headers.c>\n    Header set Cache-Control \"public, max-age=31536000, immutable\"\n  </IfModule>\n  <IfModule !mod_headers.c>\n    <IfModule mod_expires.c>\n      ExpiresActive On\n      ExpiresDefault \"access plus 1 year\"\n    </IfModule>\n  </IfModule>\n</FilesMatch>\n";

/// TypedPress's plugins for this app, in the order WordPress must activate them: the runtime, then the
/// plugins that require it.
pub(crate) fn tp_plugins(schema: &schema::Schema) -> Vec<String> {
    let mut slugs = vec![
        "typedpress-runtime".to_string(),
        "typedpress-identity".to_string(),
        format!("typedpress-app-{}", schema.name),
    ];
    if schema.admin {
        slugs.push("typedpress-admin".to_string());
    }
    slugs
}

pub(crate) fn readme(slug: &str) -> String {
    format!(
        "=== {slug} ===\nStable tag: {}\nLicense: GPL-2.0-or-later\n",
        env!("CARGO_PKG_VERSION")
    )
}

pub(crate) fn plugin_vars(schema: &schema::Schema, schema_php: &str) -> Vec<(&'static str, String)> {
    let hash = {
        // FNV-1a: a stable fingerprint of the built schema (changes when the plugin must migrate).
        let mut h: u64 = 0xcbf2_9ce4_8422_2325;
        for b in schema_php.bytes() {
            h ^= u64::from(b);
            h = h.wrapping_mul(0x0100_0000_01b3);
        }
        format!("{h:016x}")
    };
    let label = schema::title_case(&schema.name);
    vec![
        ("name", schema.name.clone()),
        ("slug", format!("typedpress-app-{}", schema.name)),
        ("runtimeSeries", platform::SERIES.to_string()),
        ("wpVersion", platform::WORDPRESS.to_string()),
        ("phpVersion", platform::PHP.to_string()),
        (
            "requires",
            platform::app_plugins(schema.locales.is_some(), schema.store.is_some())
                .into_iter()
                .map(|p| p.slug)
                .chain(["typedpress-runtime".to_string()])
                .collect::<Vec<_>>()
                .join(", "),
        ),
        ("label", label.clone()),
        ("Name", label),
        ("version", env!("CARGO_PKG_VERSION").to_string()),
        ("schemaHash", hash),
        ("tpVersion", env!("CARGO_PKG_VERSION").to_string()),
    ]
}

/// `{{key}}` → value. Unknown placeholders are left as they are.
pub(crate) fn substitute(text: &str, vars: &[(&'static str, String)]) -> String {
    let mut out = text.to_string();
    for (k, v) in vars {
        out = out.replace(&format!("{{{{{k}}}}}"), v);
    }
    out
}
