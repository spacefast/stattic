//! Files that components and pages import and that are not code (docs/decisions/2026-11-08-tsx-to-php.md,
//! "CSS"; docs/spec/tsx-to-php.md, "Accepted"):
//! - `import "./site.css"`: a stylesheet, copied as it is and linked on every page whose page or
//!   layouts reach the import;
//! - `import styles from "./note.module.css"`: a CSS module, its class selectors renamed to
//!   `<file stem>_<class>` (`note_dek`), as `packages/pages` names them, and `styles.dek` the new
//!   name; linked like a stylesheet;
//! - `import logo from "./compass.svg"`: copied, and the import's value is the file's URL. Source
//!   bundles carry text, so only SVG imports; a binary image is a `public/` file, by its URL.
//!
//! Every output file is named `<stem>-<hash>.<ext>` from a SHA-256 of its bytes, under the app
//! plugin's `tp/app/assets/`, so a changed file gets a new URL and an old one never changes:
//! the folder's `.htaccess` lets Apache cache them for a year.

use crate::diag::{Diag, Result, Span};
use indexmap::IndexMap;
use sha2::{Digest, Sha256};
use std::path::Path;

/// The extensions an import may name besides code, for the "can't import" help.
pub const EXTENSIONS: &[&str] = &[".css", ".module.css", ".svg"];

/// Where the app plugin keeps them, below its root.
pub const DIR: &str = "tp/app/assets";

/// Served by Apache with a year's cache; the names change whenever the bytes do.
pub const HTACCESS: &str = "# Generated by `typedpress build`. Every file here is named by a hash of its bytes.\n<IfModule mod_headers.c>\n  Header set Cache-Control \"public, max-age=31536000, immutable\"\n</IfModule>\n<IfModule !mod_headers.c>\n  <IfModule mod_expires.c>\n    ExpiresActive On\n    ExpiresDefault \"access plus 1 year\"\n  </IfModule>\n</IfModule>\n";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    Css,
    CssModule,
    Image,
}

/// The kind of file `path` names, if it is an asset.
pub fn kind(path: &Path) -> Option<Kind> {
    let name = path.file_name()?.to_str()?.to_ascii_lowercase();
    if name.ends_with(".module.css") {
        Some(Kind::CssModule)
    } else if name.ends_with(".css") {
        Some(Kind::Css)
    } else if name.ends_with(".svg") {
        Some(Kind::Image)
    } else {
        None
    }
}

#[derive(Debug, Clone)]
pub struct Asset {
    pub kind: Kind,
    /// The source path, relative to the project root.
    pub source: String,
    /// The output file name below [`DIR`].
    pub file: String,
    /// The output bytes: a CSS module's renamed text, anything else as read.
    pub bytes: Vec<u8>,
    /// A CSS module's classes: source name → output name, in selector order.
    pub classes: IndexMap<String, String>,
    /// A CSS module's source text, which a renumbered class is renamed from again.
    original: Option<String>,
}

/// A file stem as a CSS identifier part: `my-card.module.css` → `my_card`, as esbuild names it.
fn stem(source: &str, kind: Kind) -> String {
    let name = source.rsplit('/').next().unwrap_or(source);
    let base = match kind {
        Kind::CssModule => &name[..name.len() - ".module.css".len()],
        _ => name.rsplit_once('.').map_or(name, |(b, _)| b),
    };
    let out: String = base
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' })
        .collect();
    if out.is_empty() { "asset".into() } else { out }
}

fn hash(bytes: &[u8]) -> String {
    crate::hex(&Sha256::digest(bytes)[..8])
}

impl Asset {
    /// Reads one imported file. `file` is the diagnostic file id of its text.
    pub fn new(source: &str, kind: Kind, bytes: Vec<u8>, file: u32) -> Result<Self> {
        let mut classes = IndexMap::new();
        let mut original = None;
        let bytes = match kind {
            Kind::Image => bytes,
            Kind::Css | Kind::CssModule => {
                let text = String::from_utf8(bytes).map_err(|_| {
                    Diag::new(Span { file, start: 0, end: 0 }, format!("{source} isn't UTF-8 text"))
                        .code(crate::diag::Code::Import)
                })?;
                let scanned = crate::css::scan(&text, kind == Kind::CssModule).map_err(|r| {
                    Diag::new(
                        Span {
                            file,
                            start: r.at as u32,
                            end: r.at as u32 + 1,
                        },
                        r.message,
                    )
                    .help(r.help)
                    .code(crate::diag::Code::Import)
                })?;
                if kind == Kind::CssModule {
                    let prefix = stem(source, kind);
                    for (_, _, class) in &scanned.classes {
                        classes
                            .entry(class.clone())
                            .or_insert_with(|| format!("{prefix}_{class}"));
                    }
                    let renamed = crate::css::rename(&text, &scanned, |c| classes[c].clone()).into_bytes();
                    original = Some(text);
                    renamed
                } else {
                    text.into_bytes()
                }
            }
        };
        let extension = match kind {
            Kind::Css | Kind::CssModule => "css".to_string(),
            Kind::Image => source.rsplit_once('.').map_or("bin", |(_, e)| e).to_ascii_lowercase(),
        };
        Ok(Asset {
            kind,
            source: source.to_string(),
            file: format!("{}-{}.{extension}", stem(source, kind).replace('_', "-"), hash(&bytes)),
            bytes,
            classes,
            original,
        })
    }
}

/// Two CSS modules may give a class the same output name (`a/note.module.css` and
/// `b/note.module.css` both define `.title`). The later one, in source-path order, takes a
/// numbered name (`note_title2`), as esbuild numbers them; the renamed text and its file name follow.
pub fn dedupe(assets: &mut [&mut Asset]) {
    assets.sort_by(|a, b| a.source.cmp(&b.source));
    let mut taken: std::collections::HashSet<String> = std::collections::HashSet::new();
    for asset in assets.iter_mut() {
        if asset.kind != Kind::CssModule {
            continue;
        }
        let mut renamed = false;
        for (_, out) in asset.classes.iter_mut() {
            if taken.insert(out.clone()) {
                continue;
            }
            let mut n = 2;
            while taken.contains(&format!("{out}{n}")) {
                n += 1;
            }
            *out = format!("{out}{n}");
            taken.insert(out.clone());
            renamed = true;
        }
        if renamed {
            let original = asset.original.as_deref().expect("a CSS module keeps its text");
            let scanned = crate::css::scan(original, true).expect("scanned once already");
            asset.bytes = crate::css::rename(original, &scanned, |c| asset.classes[c].clone()).into_bytes();
            asset.file = format!(
                "{}-{}.css",
                stem(&asset.source, asset.kind).replace('_', "-"),
                hash(&asset.bytes)
            );
        }
    }
}

/// The stylesheets a route links: every CSS and CSS-module asset its layouts and page reach
/// through imports, each once, dependencies before the module that imports them and in import
/// order (as a bundler orders them), the root layout's first.
pub fn stylesheets(program: &crate::loader::Program, roots: &[usize]) -> Vec<String> {
    let mut out = Vec::new();
    let mut seen = std::collections::HashSet::new();
    fn visit(
        program: &crate::loader::Program,
        id: usize,
        seen: &mut std::collections::HashSet<usize>,
        out: &mut Vec<String>,
    ) {
        if !seen.insert(id) {
            return;
        }
        if let Some(asset) = program.assets.get(&id) {
            if asset.kind != Kind::Image {
                out.push(asset.file.clone());
            }
            return;
        }
        for stmt in &program.modules[id].body {
            let source = match stmt {
                crate::ir::Stmt::Import {
                    source,
                    type_only: false,
                    ..
                }
                | crate::ir::Stmt::ExportNames { from: Some(source), .. }
                | crate::ir::Stmt::ExportAll { from: source, .. } => source,
                _ => continue,
            };
            if let Some(&target) = program.resolved.get(&(id, source.clone())) {
                visit(program, target, seen, out);
            }
        }
    }
    for &root in roots {
        visit(program, root, &mut seen, &mut out);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn asset(source: &str, text: &str) -> Asset {
        Asset::new(source, kind(Path::new(source)).unwrap(), text.as_bytes().to_vec(), 0).unwrap()
    }

    #[test]
    fn css_module_classes_take_the_file_stem_as_packages_pages_named_them() {
        let a = asset(
            "tp/app/notes/[slug]/note.module.css",
            ".note { a: 1 }\n.dek, .note .back { b: 2 }\n",
        );
        assert_eq!(
            a.classes
                .iter()
                .map(|(k, v)| (k.as_str(), v.as_str()))
                .collect::<Vec<_>>(),
            [("note", "note_note"), ("dek", "note_dek"), ("back", "note_back")]
        );
        assert_eq!(
            String::from_utf8(a.bytes.clone()).unwrap(),
            ".note_note { a: 1 }\n.note_dek, .note_note .note_back { b: 2 }\n"
        );
        assert!(a.file.starts_with("note-") && a.file.ends_with(".css"), "{}", a.file);
        assert_eq!(stem("tp/components/my-card.module.css", Kind::CssModule), "my_card");
        assert_eq!(stem("tp/components/Nav.Item.module.css", Kind::CssModule), "Nav_Item");
    }

    #[test]
    fn a_class_two_modules_share_gets_a_number_in_the_later_one() {
        let mut a = asset("tp/components/b/note.module.css", ".title { color: blue }");
        let mut b = asset("tp/components/a/note.module.css", ".title { color: red } .x {}");
        let before = b.file.clone();
        dedupe(&mut [&mut a, &mut b]);
        assert_eq!(b.classes["title"], "note_title", "a/ sorts first and keeps the name");
        assert_eq!(a.classes["title"], "note_title2");
        assert_eq!(
            String::from_utf8(a.bytes.clone()).unwrap(),
            ".note_title2 { color: blue }"
        );
        assert_eq!(b.file, before);
    }

    #[test]
    fn names_follow_the_bytes() {
        let a = asset("tp/app/site.css", "body { margin: 0 }");
        let b = asset("tp/app/site.css", "body { margin: 1px }");
        assert_ne!(a.file, b.file);
        assert!(a.file.starts_with("site-"));
        let svg = Asset::new("tp/app/about/compass.svg", Kind::Image, b"<svg/>".to_vec(), 0).unwrap();
        assert!(svg.file.starts_with("compass-") && svg.file.ends_with(".svg"));
    }
}
