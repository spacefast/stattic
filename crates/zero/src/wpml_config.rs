//! `wpml-config.xml` for the generated app plugin (§7.3): tells Polylang (and WPML) which post types
//! are translatable and, per SCF meta key, whether a new translation copies it (synced columns) or
//! translates it (localized columns). uid is per row. Zero syncs synced columns itself in the
//! pipeline; this file makes wp-admin's own "+ translation" button behave the same way.

use crate::schema::{Collection, Schema};
use std::fmt::Write as _;

fn xml(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// The file's text, or `None` when no post-backed collection is localized.
pub fn render(schema: &Schema) -> Option<String> {
    let collections: Vec<&Collection> = schema
        .collections
        .values()
        .filter(|c| c.localized && c.editor)
        .collect();
    if schema.locales.is_none() || collections.is_empty() {
        return None;
    }
    let mut out = String::from(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- Generated by `zero build` from zero.config.ts. Do not edit. -->\n<wpml-config>\n  <custom-types>\n",
    );
    for c in &collections {
        let _ = writeln!(
            out,
            "    <custom-type translate=\"1\">zero_{}</custom-type>",
            xml(&c.table)
        );
    }
    out.push_str("  </custom-types>\n  <custom-fields>\n");
    let mut seen = std::collections::BTreeMap::new();
    for c in &collections {
        for col in c.columns.values().filter(|col| !c.is_core_column(&col.name)) {
            // Generated per row (default now/fn, onUpdate) like createdAt/updatedAt: never copied.
            let generated = col.on_update.is_some()
                || matches!(
                    col.default,
                    Some(crate::schema::DefaultKind::Now | crate::schema::DefaultKind::Fn(_))
                );
            let action = if col.translated() {
                "translate"
            } else if generated {
                "ignore"
            } else {
                "copy"
            };
            let nested = col.fields.is_some() || col.layouts.is_some();
            for key in [format!("zero_{}", col.name)]
                .into_iter()
                .chain(nested.then(|| format!("zero_{}_*", col.name)))
            {
                // One action per meta key: two collections disagreeing on a shared key is untranslatable.
                seen.entry(key).or_insert(action);
            }
        }
    }
    for (key, action) in &seen {
        let _ = writeln!(out, "    <custom-field action=\"{action}\">{}</custom-field>", xml(key));
    }
    out.push_str("    <custom-field action=\"ignore\">_zero_uid</custom-field>\n  </custom-fields>\n</wpml-config>\n");
    Some(out)
}
